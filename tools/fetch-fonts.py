"""
Downloads the two DESIGN.md typefaces as self-hosted woff2 subsets and regenerates
apps/web/src/app/fonts.css.

Self-hosted rather than next/font because tokens.ts carries the *literal* family names
("Unbounded", "IBM Plex Mono") — next/font would rename them to hashed families and every
inline style in @sporim/ui would silently fall back. Literal names also keep the same
components renderable by satori.

Run from the repo root:  python tools/fetch-fonts.py
"""

from __future__ import annotations

import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "apps" / "web" / "public" / "fonts"
CSS_OUT = ROOT / "apps" / "web" / "src" / "app" / "fonts.css"

UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/131.0 Safari/537.36"
)
CSS_URL = (
    "https://fonts.googleapis.com/css2?family=Unbounded:wght@700;900"
    "&family=IBM+Plex+Mono:wght@400;600&display=swap"
)

# Only these subsets ship: latin for the product, cyrillic because the terms of a bet
# are user-written and this audience writes Russian.
SUBSETS = {
    "U+0000-00FF": "latin",
    "U+0100-02BA": "latin-ext",
    "U+0301, U+0400-045F": "cyrillic",
}
SLUG = {"Unbounded": "unbounded", "IBM Plex Mono": "plexmono"}


def fetch(url: str, dest: pathlib.Path | None = None) -> str:
    cmd = ["curl", "-s", "--max-time", "40", "-A", UA, url]
    if dest is not None:
        subprocess.run([*cmd, "-o", str(dest)], check=True)
        return ""
    return subprocess.run(cmd, capture_output=True, text=True, check=True).stdout


def main() -> None:
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    css = fetch(CSS_URL)

    faces = []
    for block in re.findall(r"@font-face\s*\{(.*?)\}", css, re.S):
        family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        weight = re.search(r"font-weight:\s*(\d+)", block).group(1)
        url = re.search(r"url\((https://[^)]+)\)", block).group(1)
        unicode_range = re.search(r"unicode-range:\s*([^;]+);", block).group(1).strip()
        subset = next((v for k, v in SUBSETS.items() if unicode_range.startswith(k)), None)
        if subset is None:
            continue
        faces.append((f"{SLUG[family]}-{weight}-{subset}.woff2", url, family, weight, unicode_range))

    for name, url, *_ in faces:
        fetch(url, FONT_DIR / name)
        print(f"{name}  {(FONT_DIR / name).stat().st_size} bytes")

    rules = [
        "@font-face {\n"
        f"  font-family: '{family}';\n"
        "  font-style: normal;\n"
        f"  font-weight: {weight};\n"
        "  font-display: swap;\n"
        f"  src: url('/fonts/{name}') format('woff2');\n"
        f"  unicode-range: {unicode_range};\n"
        "}"
        for name, _url, family, weight, unicode_range in faces
    ]
    CSS_OUT.write_text(
        "/*\n"
        " * Generated by tools/fetch-fonts.py — do not edit by hand.\n"
        " * Self-hosted so the literal family names in @sporim/ui tokens resolve and no\n"
        " * third-party font request survives the CSP.\n"
        " */\n\n" + "\n\n".join(rules) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {CSS_OUT.relative_to(ROOT)} with {len(faces)} faces")


if __name__ == "__main__":
    main()
